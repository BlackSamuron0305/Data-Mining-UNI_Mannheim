def tex_escape(text: str) -> str:
    return str(text).replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def _fmt(v, digits: int = 4, pct: bool = False) -> str:
    if v is None or pd.isna(v):
        return "--"
    val = float(v) * (100.0 if pct else 1.0)
    return f"{val:.{digits}f}"


def _write_table(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")


def build_tab_results(res: pd.DataFrame, iv: pd.DataFrame | None, top_col: str) -> str:
    t = res[(res["part"] == "test") & (res["moves_on"] == "common")].sort_values("log_loss")
    iv_map = iv.set_index(["run", "score"]) if (iv is not None and len(iv)) else None
    p_col = f"precision_{top_col}"
    l_col = f"lift_{top_col}"
    lines = [
        "% Auto-generated by src.05_evaluation.report_assets",
        "\\begin{tabular}{@{}lrrrrrrrrrrrr@{}}",
        "  \\toprule",
        "  Run & PR-AUC (95\\% CI) & ROC-AUC & Log loss & BSS & ECE & Acc & Prec & Rec & F1 & F0.5 & P@5\\% & Lift@5\\% \\\\",
        "  \\midrule",
    ]
    for _, r in t.iterrows():
        run = str(r["run"])
        pr_str = _fmt(r.get("pr_auc"), 3)
        if iv_map is not None and (run, "pr_auc") in iv_map.index:
            ci = iv_map.loc[(run, "pr_auc")]
            pr_str = f"{float(ci['estimate']):.3f} [{float(ci['lo']):.3f}, {float(ci['hi']):.3f}]"
        bss = r.get("brier_skill_vs_baseline")
        if pd.isna(bss):
            bss = r.get("brier_skill")
        row_cells = [
            tex_escape(run),
            pr_str,
            _fmt(r.get("roc_auc"), 3),
            _fmt(r.get("log_loss"), 4),
            _fmt(bss, 3),
            _fmt(r.get("ece"), 3),
            _fmt(r.get("accuracy"), 1, pct=True) + "\\%",
            _fmt(r.get("precision"), 1, pct=True) + "\\%",
            _fmt(r.get("recall"), 1, pct=True) + "\\%",
            _fmt(r.get("f1"), 3),
            _fmt(r.get("f05"), 3),
            _fmt(r.get(p_col), 1, pct=True) + "\\%",
            _fmt(r.get(l_col), 2),
        ]
        lines.append("  " + " & ".join(row_cells) + " \\\\")
    lines += ["  \\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def _split_method_feature(run: str) -> tuple[str, str]:
    clean = run.split(":", 1)[-1]
    method, variant = clean.rsplit("/", 1) if "/" in clean else (clean, "context")
    if "engine" in variant:
        return method, "engine"
    if "context" in variant:
        return method, "context"
    return method, "single"


def build_tab_results_slide(res: pd.DataFrame, top_col: str) -> str:
    t = res[(res["part"] == "test") & (res["moves_on"] == "common")].copy()
    t = t[~t["run"].astype(str).str.contains(":")]
    t = t[~t["run"].astype(str).str.startswith("ablation/")]
    l_col = f"lift_{top_col}"
    best_slot: dict[tuple[str, str], pd.Series] = {}
    order_methods: list[str] = []
    for _, r in t.sort_values("log_loss").iterrows():
        method, slot = _split_method_feature(str(r["run"]))
        if method not in order_methods:
            order_methods.append(method)
        if (method, slot) not in best_slot:
            best_slot[(method, slot)] = r

    lines = [
        "% Auto-generated by src.05_evaluation.report_assets",
        "\\begin{tabular}{@{}lrrr@{}}",
        "  \\toprule",
        "   & \\multicolumn{2}{c}{PR-AUC} & Lift \\\\",
        "  Method & context & engine & top 5\\% \\\\",
        "  \\midrule",
    ]
    for method in order_methods:
        label = PRETTY_METHOD.get(method, tex_escape(method.replace("_", " ").title()))
        if (method, "single") in best_slot and (method, "context") not in best_slot and (method, "engine") not in best_slot:
            row = best_slot[(method, "single")]
            lines.append(
                f"  {label} & \\multicolumn{{2}}{{c}}{{{_fmt(row.get('pr_auc'), 3)}}} & {_fmt(row.get(l_col), 2)} \\\\"
            )
        else:
            rc = best_slot.get((method, "context"))
            re = best_slot.get((method, "engine"))
            lift_row = re if re is not None else rc
            lines.append(
                f"  {label} & {_fmt(rc.get('pr_auc') if rc is not None else np.nan, 3)} & "
                f"{_fmt(re.get('pr_auc') if re is not None else np.nan, 3)} & "
                f"{_fmt(lift_row.get(l_col) if lift_row is not None else np.nan, 2)} \\\\"
            )
    lines += ["  \\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def build_tab_metric_justification() -> str:
    rows = [
        ("PR-AUC", "Primary (Ranking)", "Area under precision--recall curve; emphasizes rare blunder class (\\textasciitilde{}5.5\\%) without true-negative inflation."),
        ("Log loss", "Primary (Probability)", "Strictly proper scoring rule; penalizes overconfident errors and guides validation early stopping."),
        ("Brier / BSS / ECE", "Primary (Calibration)", "Measures squared probability error, skill over baseline, and 20-bin reliability gap."),
        ("ROC-AUC", "Secondary (Ranking)", "Threshold-free ranking reference; insensitive to class imbalance compared with PR-AUC."),
        ("Accuracy", "Diagnostic (Paradox)", "Reported to expose the Accuracy Paradox (~94.5\\% by predicting never-blunder with 0\\% recall)."),
        ("Precision, Recall, $F_1$, $F_{0.5}$, MCC", "Secondary (Threshold)", "Trade-offs at validation cutoffs; $F_{0.5}$ weights precision 2$\\times$ over recall for low-fatigue alerts."),
        ("Top-$K$\\% Prec / Rec / Lift", "Secondary (Budgeted)", "Measures blunder concentration under fixed broadcast or coaching alert budgets (1\\%--10\\%)."),
    ]
    lines = [
        "% Auto-generated by src.05_evaluation.report_assets",
        "\\begin{tabular}{@{}llr@{}}",
        "  \\toprule",
        "  Metric & Role & Justification \\\\",
        "  \\midrule",
    ]
    for name, role, desc in rows:
        lines.append(f"  {name} & {role} & {desc} \\\\")
    lines += ["  \\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def build_tab_operating_points(op_df: pd.DataFrame) -> str:
    df = op_df.copy()
    if "run" in df.columns and len(df):
        first_run = df["run"].iloc[0]
        df = df[df["run"] == first_run]
    policy_labels = {
        "majority_never_blunder": "Majority (never blunder)",
        "valid_max_f1": "Valid Max-$F_1$",
        "valid_max_f05": "Valid Max-$F_{0.5}$",
        "valid_prec_35": "Valid Prec $\\ge 35\\%$",
        "valid_prec_50": "Valid Prec $\\ge 50\\%$",
        "top_1pct": "Top 1\\% budget",
        "top_2pct": "Top 2\\% budget",
        "top_3pct": "Top 3\\% budget",
        "top_5pct": "Top 5\\% budget",
        "top_10pct": "Top 10\\% budget",
    }
    lines = [
        "% Auto-generated by src.05_evaluation.report_assets",
        "\\begin{tabular}{@{}lrrrrrrrr@{}}",
        "  \\toprule",
        "  Policy & Cutoff & Flagged & Acc & Prec & Rec & F1 & F0.5 & Lift \\\\",
        "  \\midrule",
    ]
    for _, r in df.iterrows():
        p_name = str(r["policy"])
        label = policy_labels.get(p_name, tex_escape(p_name))
        cells = [
            label,
            _fmt(r.get("cutoff"), 3),
            _fmt(r.get("flagged"), 1, pct=True) + "\\%",
            _fmt(r.get("accuracy"), 1, pct=True) + "\\%",
            _fmt(r.get("precision"), 1, pct=True) + "\\%",
            _fmt(r.get("recall"), 1, pct=True) + "\\%",
            _fmt(r.get("f1"), 3),
            _fmt(r.get("f05"), 3),
            _fmt(r.get("lift"), 2),
        ]
        lines.append("  " + " & ".join(cells) + " \\\\")
    lines += ["  \\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def build_tab_ablation(res: pd.DataFrame, runs_dir: Path) -> str | None:
    abl_root = runs_dir / "ablation"
    csvs = sorted(abl_root.glob("*/ablation.csv")) if abl_root.exists() else []
    if csvs:
        frames = [pd.read_csv(p) for p in csvs]
        df = pd.concat(frames, ignore_index=True)
        lines = [
            "% Auto-generated by src.05_evaluation.report_assets",
            "\\begin{tabular}{@{}lrrrr@{}}",
            "  \\toprule",
            "   & \\multicolumn{2}{c}{Without group} & \\multicolumn{2}{c}{Only group} \\\\",
            "  Group & PR-AUC & Log loss & PR-AUC & Log loss \\\\",
            "  \\midrule",
        ]
        groups = [g for g in pd.unique(df.get("group", [])) if str(g) != "all"]
        for g in groups:
            wo = df[(df["group"] == g) & (df["mode"] == "without")]
            on = df[(df["group"] == g) & (df["mode"] == "only")]
            pr_wo = wo["pr_auc"].iloc[0] if len(wo) else np.nan
            ll_wo = wo["log_loss"].iloc[0] if len(wo) else np.nan
            pr_on = on["pr_auc"].iloc[0] if len(on) else np.nan
            ll_on = on["log_loss"].iloc[0] if len(on) else np.nan
            label = GROUP_LABELS.get(str(g), tex_escape(str(g)))
            lines.append(f"  {label} & {_fmt(pr_wo, 3)} & {_fmt(ll_wo, 4)} & {_fmt(pr_on, 3)} & {_fmt(ll_on, 4)} \\\\")
        lines += ["  \\bottomrule", "\\end{tabular}"]
        return "\n".join(lines)

    test = res[(res["part"] == "test") & (res["moves_on"] == "common")]
    abl_rows = test[test["run"].astype(str).str.startswith("ablation/")]
    if not len(abl_rows):
        return None
    by_variant = {}
    for _, r in abl_rows.iterrows():
        variant = str(r["run"]).split("/", 1)[1]
        for token in ("_without_", "_only_", "_all"):
            if token in variant:
                if token == "_all":
                    by_variant[("all", "all")] = r
                else:
                    mode = token.strip("_")
                    grp = variant.split(token, 1)[1]
                    by_variant[(grp, mode)] = r
                break
    if not by_variant:
        return None

    lines = [
        "% Auto-generated by src.05_evaluation.report_assets",
        "\\begin{tabular}{@{}lrrrr@{}}",
        "  \\toprule",
        "   & \\multicolumn{2}{c}{Without group} & \\multicolumn{2}{c}{Only group} \\\\",
        "  Group & PR-AUC & Log loss & PR-AUC & Log loss \\\\",
        "  \\midrule",
    ]
    if ("all", "all") in by_variant:
        r0 = by_variant[("all", "all")]
        lines.append(f"  All groups & {_fmt(r0.get('pr_auc'), 3)} & {_fmt(r0.get('log_loss'), 4)} & -- & -- \\\\")
    seen_groups = []
    for grp, _ in by_variant:
        if grp != "all" and grp not in seen_groups:
            seen_groups.append(grp)
    for grp in seen_groups:
        wo = by_variant.get((grp, "without"))
        on = by_variant.get((grp, "only"))
        label = GROUP_LABELS.get(grp, tex_escape(grp))
        lines.append(
            f"  {label} & {_fmt(wo.get('pr_auc') if wo is not None else np.nan, 3)} & "
            f"{_fmt(wo.get('log_loss') if wo is not None else np.nan, 4)} & "
            f"{_fmt(on.get('pr_auc') if on is not None else np.nan, 3)} & "
            f"{_fmt(on.get('log_loss') if on is not None else np.nan, 4)} \\\\"
        )
    lines += ["  \\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def export(
    res: pd.DataFrame,
    iv: pd.DataFrame | None,
    op_df: pd.DataFrame | None,
    out_dir: Path,
    runs_dir: Path = RUNS_DIR,
    others: list[str] | None = None,
) -> list[str]:
    """Write all booktabs LaTeX tables into out_dir/tables/ and return written filenames."""
    tables_dir = out_dir / "tables"
    top_col = top_name(CFG["evaluation"]["top_share"])
    written: list[str] = []

    _write_table(tables_dir / "tab_results.tex", build_tab_results(res, iv, top_col))
    written.append("tab_results.tex")

    _write_table(tables_dir / "tab_results_slide.tex", build_tab_results_slide(res, top_col))
    written.append("tab_results_slide.tex")

    _write_table(tables_dir / "tab_metric_justification.tex", build_tab_metric_justification())
    written.append("tab_metric_justification.tex")

    if op_df is not None and len(op_df):
        _write_table(tables_dir / "tab_operating_points.tex", build_tab_operating_points(op_df))
        written.append("tab_operating_points.tex")

    ablation_tex = build_tab_ablation(res, runs_dir)
    if ablation_tex is not None:
        _write_table(tables_dir / "tab_ablation.tex", ablation_tex)
        written.append("tab_ablation.tex")

    return written


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dir", type=Path, default=VALIDATION_DIR, help="evaluation directory containing results.csv")
    ap.add_argument("--runs-dir", type=Path, default=RUNS_DIR, help="runs directory for ablation lookup")
    args = ap.parse_args()

    res = pd.read_csv(args.dir / "results.csv")
    iv_path = args.dir / "intervals.csv"
    iv = pd.read_csv(iv_path) if iv_path.exists() else None
    op_path = args.dir / "operating_points.csv"
    op_df = pd.read_csv(op_path) if op_path.exists() else None
    names = export(res, iv, op_df, args.dir, runs_dir=args.runs_dir)
    print(f"Wrote {len(names)} tables to {args.dir / 'tables'}: {', '.join(names)}")


if __name__ == "__main__":
    main()
